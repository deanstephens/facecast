// Bundles Trystero (serverless WebRTC signalling) into single ES modules inside the web template, so the page
// needs no CDN and no build step of its own. Run after changing the Trystero version in package.json:
//
//   cd Tools/web && npm install && npm run vendor
//
// Nostr is the default signalling network; MQTT is the fallback the page can switch to with ?net=mqtt.

import {build} from 'esbuild'
import {fileURLToPath} from 'node:url'
import path from 'node:path'
import fs from 'node:fs'

const here = path.dirname(fileURLToPath(import.meta.url))
const outDir = path.resolve(here, '../../Assets/WebGLTemplates/Facecast/lib')
const version = JSON.parse(fs.readFileSync(path.join(here, 'node_modules/@trystero-p2p/nostr/package.json'), 'utf8')).version

for (const strategy of ['nostr', 'mqtt']) {
  const outfile = path.join(outDir, `trystero-${strategy}.js`)
  await build({
    stdin: {contents: `export * from '@trystero-p2p/${strategy}'`, resolveDir: here, loader: 'js'},
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'inline',
    banner: {js: `// Trystero ${version} (${strategy} strategy), MIT licence, https://github.com/dmotz/trystero. Generated by Tools/web/vendor.mjs.`},
    outfile,
  })
  console.log(`${path.relative(process.cwd(), outfile)}  ${(fs.statSync(outfile).size / 1024).toFixed(0)} KB`)
}
